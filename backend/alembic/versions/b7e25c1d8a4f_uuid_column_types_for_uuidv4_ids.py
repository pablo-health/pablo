"""Convert UUIDv4-shaped String(128) ID columns to native Postgres UUID

Every domain ID generated by the app as ``str(uuid.uuid4())`` was stored
in a ``VARCHAR(128)`` column. Native ``UUID`` is 16 bytes vs 37 bytes per
row, indexes more compactly, and rejects malformed values at the DB
level. This migration converts those columns in place; the data parses
because every existing row holds a UUID4 string.

Scope (PHI and admin tables whose ``id`` is uuid4()):

  patients.id
  therapy_sessions.id, .patient_id
  notes.id, .patient_id, .session_id
  appointments.id, .patient_id, .session_id, .recurring_appointment_id
  availability_rules.id
  compliance_items.id
  compliance_documents.id, .compliance_item_id
  chat_conversations.id, .patient_id
  chat_messages.id, .conversation_id
  audit_logs.id, .patient_id, .session_id
  patient_clinicians.patient_id
  ical_client_mappings.patient_id
  compliance_reminder_dispatches.compliance_item_id  (saas-overlay table; no-op when absent)
  platform.platform_audit_logs.id

Explicitly NOT converted:

  *.user_id (Firebase uid, not a uuid; deferred to Phase C)
  audit_logs.resource_id (polymorphic; holds user_id when the
                          resource is a user, so cannot be UUID)
  practice/tenant slugs and other opaque strings

Each ALTER is wrapped in a guard so it is a no-op when the column is
already ``uuid`` — this matters because Alembic per-tenant fan-out
replays platform-schema DDL against every tenant connection, and
because env.py's ``create_all`` on a fresh deploy will already have
materialised the platform tables with the new model types.

Foreign-key constraints touching the converted columns must be
dropped before altering and re-created afterward — Postgres rejects
an ALTER COLUMN TYPE that would leave an FK with incompatible
parent/child types, even when both sides are being altered in the
same transaction (only DEFERRABLE constraints get the deferred-check
treatment, and these are not declared DEFERRABLE). The drop/recreate
is automated via pg_constraint / pg_get_constraintdef so we don't
have to maintain a hardcoded FK list as the schema evolves.

Revision ID: b7e25c1d8a4f
Revises: a4c91b6e3f08
Create Date: 2026-05-14
"""

