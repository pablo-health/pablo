def _alter_to_uuid_in_current_schema(table: str, column: str) -> None:
    """ALTER TABLE <current_schema>.<table>.<column> TYPE uuid, idempotent."""
    # Identifiers are module-level constants, not user input
    sql = f"""DO $$
        BEGIN
            IF EXISTS (
                SELECT 1 FROM information_schema.columns
                WHERE table_schema = current_schema()
                  AND table_name = '{table}'
                  AND column_name = '{column}'
                  AND data_type = 'character varying'
            ) THEN
                EXECUTE 'ALTER TABLE {table}
                         ALTER COLUMN {column} TYPE uuid
                         USING {column}::uuid';
            END IF;
        END $$;"""  # noqa: S608
    op.execute(sql)


