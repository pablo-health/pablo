"""LLM-judge faithfulness scorer (THERAPY-03m0 spike).

Tier-2 scorer per backend/evals/DESIGN.md §2. Asks an LLM to compare
a generated SOAP note against the transcript it was produced from
(and optionally a reference SOAP), and return a structured verdict:

  - hallucinated_facts: assertions in the generated note that the
    transcript does not support.
  - missing_facts: facts present in the reference SOAP (if provided)
    or clearly stated in the transcript that the generated note
    omits.
  - passes: True iff hallucinated_facts is empty AND missing_facts
    contains no items the judge flagged as clinically critical.

Designed for the Braintrust scorer contract (see DESIGN.md §5). For
the spike, the runner at backend/evals/spike_judge.py invokes
score() directly.

Out of scope for the spike:
  - Threshold tuning (judges' verdicts are accepted as-is today).
  - Ensembling across multiple judges.
  - Cost/latency optimization.
  - Wiring to Braintrust scheduled experiments.
"""

from __future__ import annotations

import json
import logging
import re
from dataclasses import dataclass
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from backend.app.services.structured_llm_gateway import StructuredLLMGateway

logger = logging.getLogger(__name__)

# Default judge model. Gemini 3.5 GA's pro variant is not yet released
# (only `gemini-3.5-flash` is GA as of 2026-05-23); flash is competitive
# on the spike fixtures (caught all planted hallucinations + adjacent
# overreach) and is cheap enough for routine schedule runs. Swap to
# `gemini-3.5-pro` when it ships. Never use Gemini 2.5.
_DEFAULT_JUDGE_MODEL = "gemini-3.5-flash"

# Require the four verdict keys. A bare ``{"type": "object"}`` is satisfied
# by ``{}`` — and Gemini-3.5-flash *does* return an empty object on a large
# audit input (28k transcript + 10k SOAP), silently defaulting every verdict
# to fail. Naming the fields + ``required`` forces the model to populate them;
# array items stay loosely typed (the prompt fixes their inner shape).
_JUDGE_RESPONSE_SCHEMA: dict[str, Any] = {
    "type": "object",
    "properties": {
        "hallucinated_facts": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "claim": {"type": "string"},
                    "where": {"type": "string"},
                    "why_unsupported": {"type": "string"},
                },
            },
        },
        "missing_facts": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "fact": {"type": "string"},
                    "criticality": {"type": "string"},
                    "why_critical": {"type": "string"},
                },
            },
        },
        "passes": {"type": "boolean"},
        "judge_notes": {"type": "string"},
    },
    "required": ["hallucinated_facts", "missing_facts", "passes", "judge_notes"],
}


_JUDGE_SYSTEM_PROMPT = """\
You are a clinical-documentation auditor. Your job is to evaluate a SOAP note generated by an AI from a therapy session transcript. You will identify (1) assertions in the SOAP note that are NOT supported by the transcript ("hallucinations"), and (2) clinically-critical facts that ARE in the transcript but are missing from the SOAP note ("omissions").

You must be CONSERVATIVE about hallucination calls: a paraphrase of something the patient said is not a hallucination; a reasonable clinical inference from explicit transcript content is not a hallucination. Flag only assertions that the transcript does not support — invented diagnoses, fabricated medications, escalated risk levels that the patient explicitly denied, treatment plans that were never discussed, etc.

You must be CONSERVATIVE about omission calls too: clinical SOAP notes are necessarily brief; not every transcript detail must appear. Flag only facts the patient stated explicitly AND that are clinically load-bearing (diagnostic criteria, safety information, medication history, agreed-upon treatment plans).

Return a single JSON object. Do not include any other text in your response."""  # noqa: E501


_JUDGE_USER_TEMPLATE = """\
## TRANSCRIPT
{transcript}

## GENERATED SOAP NOTE
{generated_soap}
{reference_block}{directives_block}
## TASK

Compare the GENERATED SOAP NOTE against the TRANSCRIPT (and the REFERENCE SOAP if provided).{directives_hint} Return JSON with this exact shape:

{{
  "hallucinated_facts": [
    {{"claim": "<verbatim or close quote from generated SOAP>", "where": "<subjective|objective|assessment|plan>", "why_unsupported": "<brief explanation of what the transcript actually says>"}}
  ],
  "missing_facts": [
    {{"fact": "<clinically-critical fact from the transcript>", "criticality": "<high|medium|low>", "why_critical": "<brief explanation>"}}
  ],
  "passes": <true if hallucinated_facts is empty AND no missing_fact has criticality='high'; otherwise false>,
  "judge_notes": "<one-paragraph summary of the verdict>"
}}

Empty lists are fine — return [] for hallucinated_facts or missing_facts if you find none. Do not include any text outside the JSON object."""  # noqa: E501


_REFERENCE_BLOCK_TEMPLATE = """
## REFERENCE SOAP (for completeness comparison)
{reference_soap}
"""


# Case-specific audit directives (the dataset's ``judge_directives``): the
# exact, known failure modes for this transcript — e.g. "do not escalate
# passive SI to active", "do not invent a medication". Injected so the judge
# checks these named traps explicitly rather than relying on generic auditing.
_DIRECTIVES_BLOCK_TEMPLATE = """
## AUDIT DIRECTIVES (case-specific — treat any violation as a hallucination)
{directives}
"""

_DIRECTIVES_HINT = (
    " Pay particular attention to the AUDIT DIRECTIVES — each names a known"
    " failure mode for this transcript; a note that violates one is unfaithful."
)


@dataclass
class JudgeVerdict:
    """Structured result from a single judge invocation."""

    passes: bool
    hallucinated_facts: list[dict[str, str]]
    missing_facts: list[dict[str, str]]
    judge_notes: str
    raw_response: str

    def to_dict(self) -> dict[str, Any]:
        return {
            "passes": self.passes,
            "hallucinated_facts": self.hallucinated_facts,
            "missing_facts": self.missing_facts,
            "judge_notes": self.judge_notes,
        }


def score(
    *,
    transcript: str,
    generated_soap: str,
    reference_soap: str | None = None,
    directives: list[str] | None = None,
    model: str | None = None,
    gateway: StructuredLLMGateway | None = None,
) -> JudgeVerdict:
    """Run the LLM judge once. Returns the parsed verdict.

    ``generated_soap`` may be a JSON string (e.g. SOAPNoteModel's dump)
    or a flat formatted text — the judge handles both because the
    prompt frames it as "the SOAP note." For the spike, fixtures are
    JSON with four section keys.

    ``directives`` are the case's ``judge_directives`` — the named,
    known failure modes for this transcript (SI-escalation, fabricated
    meds, etc.). When provided they're injected so the judge audits each
    one explicitly; a violation counts as a hallucination.

    ``model`` defaults to ``_DEFAULT_JUDGE_MODEL`` (gemini-3.5-flash)
    when not specified. ``gateway`` is injectable for tests; production
    callers leave it ``None`` to use the process-wide singleton.
    """
    # Local import to keep the gateway off the module-load path so
    # eval-only consumers don't pay it during import.
    from backend.app.services.structured_llm_gateway import (  # noqa: PLC0415
        get_default_structured_llm_gateway,
    )

    reference_block = (
        _REFERENCE_BLOCK_TEMPLATE.format(reference_soap=reference_soap) if reference_soap else ""
    )
    directives_block = (
        _DIRECTIVES_BLOCK_TEMPLATE.format(directives="\n".join(f"- {d}" for d in directives))
        if directives
        else ""
    )
    user_prompt = _JUDGE_USER_TEMPLATE.format(
        transcript=transcript,
        generated_soap=generated_soap,
        reference_block=reference_block,
        directives_block=directives_block,
        directives_hint=_DIRECTIVES_HINT if directives else "",
    )

    gw = gateway or get_default_structured_llm_gateway()
    try:
        completion = gw.complete_structured(
            model=model or _DEFAULT_JUDGE_MODEL,
            system_prompt=_JUDGE_SYSTEM_PROMPT,
            user_prompt=user_prompt,
            response_schema=_JUDGE_RESPONSE_SCHEMA,
            max_output_tokens=4096,
            temperature=0.0,
        )
        parsed = completion.data
        raw = json.dumps(parsed)
    except ValueError as exc:
        # Gateway raised on invalid JSON — degrade to a failure verdict
        # rather than crashing the eval run.
        logger.warning("LLM judge returned unparseable output: %s", exc)
        return JudgeVerdict(
            passes=False,
            hallucinated_facts=[],
            missing_facts=[],
            judge_notes=f"Judge returned unparseable output: {exc}",
            raw_response="",
        )

    return JudgeVerdict(
        passes=bool(parsed.get("passes", False)),
        hallucinated_facts=parsed.get("hallucinated_facts") or [],
        missing_facts=parsed.get("missing_facts") or [],
        judge_notes=str(parsed.get("judge_notes") or ""),
        raw_response=raw,
    )


def _parse_judge_response(raw: str) -> dict[str, Any]:
    """Extract the JSON object from the judge's response.

    The judge is instructed to return only JSON, but production LLM
    output occasionally wraps it in markdown fences or leading prose.
    We try strict parse first, then a fenced-block extraction, then
    the largest brace-balanced span.
    """
    text = raw.strip()
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass

    fenced = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.DOTALL)
    if fenced:
        try:
            return json.loads(fenced.group(1))
        except json.JSONDecodeError:
            pass

    first_brace = text.find("{")
    last_brace = text.rfind("}")
    if first_brace != -1 and last_brace > first_brace:
        candidate = text[first_brace : last_brace + 1]
        try:
            return json.loads(candidate)
        except json.JSONDecodeError:
            pass

    logger.warning("LLM judge returned non-JSON output; treating as failure verdict")
    return {
        "passes": False,
        "hallucinated_facts": [],
        "missing_facts": [],
        "judge_notes": f"Judge returned unparseable output: {text[:500]}",
    }


# --- Braintrust scorer adapter (for future per-case use, not the spike) ---


def llm_judge_faithfulness_scorer(
    *,
    output: str,  # noqa: ARG001 — required by Braintrust scorer contract
    expected: dict[str, Any] | None = None,
    **_kwargs: Any,
) -> dict[str, Any]:
    """Braintrust-shaped scorer wrapper.

    Activates only when ``expected`` carries a ``judge_directives`` key
    or a ``reference_soap_path`` key — the Tier-2-case marker per
    DESIGN.md §4. Other cases return ``{"score": None}`` so this
    scorer doesn't fire on Tier-1-only cases.

    NOTE: This wrapper is not exercised by the spike; the spike calls
    ``score()`` directly via spike_judge.py. The wrapper is here so
    a follow-up bead can register it into the Braintrust ``Eval()``
    pipeline without re-implementing the prompt logic.
    """
    if not isinstance(expected, dict):
        return {"name": "llm_judge_faithfulness", "score": None}
    if not (expected.get("judge_directives") or expected.get("reference_soap_path")):
        return {"name": "llm_judge_faithfulness", "score": None}

    # Production wiring needs `input` (the transcript) and a reference
    # SOAP path resolved against datasets/ — out of scope for the
    # spike. Return None until the follow-up bead wires this in.
    return {"name": "llm_judge_faithfulness", "score": None}


